using System.Globalization;
using System.Numerics;
using System.Text;
using Hosihikari.Bindings.Ir;

namespace Hosihikari.Bindings.Generator;

internal static class InteropEmitter
{
    // Keep every generated struct below the CLR field limit of 65535.
    private const int TableChunkSize = 30000;

    private static string TableFieldAccess(AbiFunction function) =>
        $"TablePtr->C{function.Index / TableChunkSize}.{function.TableField}";

    private const string DefaultStubReason = "BindingShim does not expose this member.";

    // A shell type has no usable member at all. It still carries the native type identity in
    // signatures, so it is emitted and marked obsolete instead of being dropped.
    private const string ShellTypeReason =
        "BindingShim cannot project any member of this type; it is exported for type identity only.";

    private const string EmptyEnumReason =
        "BindingShim cannot project any enumerator of this enum; it is exported for type identity only.";

    private static string StubMessage(AbiPlan plan, MemberRecord member) =>
        plan.TryGetSkipReason(member.Id, out var reason)
            ? $"BindingShim cannot project this member: {reason}."
            : DefaultStubReason;

    private static string CSharpLiteral(string value) =>
        "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    private static void EmitUnsupportedAttribute(List<string> lines, string stubMessage) =>
        lines.Add($"    [global::System.Obsolete({CSharpLiteral(stubMessage)}, false)]");

    public static void Emit(IReadOnlyList<IrRecord> records, string outputDirectory, AbiPlan plan)
    {
        var declarations = records.OfType<DeclarationRecord>()
            .Where(declaration => declaration.Kind is "class" or "struct" or "union")
            .Where(declaration => declaration.Access == "public")
            .OrderBy(declaration => declaration.Id, StringComparer.Ordinal)
            .ToList();

        var enumDeclarations = records.OfType<DeclarationRecord>()
            .Where(declaration => declaration.Kind == "enum")
            .Where(declaration => declaration.Access == "public")
            .OrderBy(declaration => declaration.Id, StringComparer.Ordinal)
            .ToList();

        var members = records.OfType<MemberRecord>()
            .GroupBy(member => member.DeclarationId, StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group.GroupBy(member => member.Id, StringComparer.Ordinal)
                    .Select(byId => byId.First())
                    .OrderBy(member => member.Id, StringComparer.Ordinal)
                    .ToList(),
                StringComparer.Ordinal);

        var declarationNames = CSharpNaming.BuildDeclarationNames(declarations);

        EmitEnums(outputDirectory, enumDeclarations, declarations, members, declarationNames);
        EmitNativeMethods(outputDirectory, plan);
        EmitVariantWrappers(outputDirectory, plan);
        EmitCallableWrappers(outputDirectory, plan);

        foreach (var declaration in declarations)
        {
            var name = declarationNames[declaration.Id];
            var hasDestroy = plan.DestroyByDeclaration.TryGetValue(declaration.Id, out var destroy);
            var hasRealFunction = plan.FunctionsByDeclaration.ContainsKey(declaration.Id);
            var classModifier = hasRealFunction ? "unsafe " : "";
            var interfaceClause = hasDestroy ? " : global::System.IDisposable" : "";
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "",
                $"namespace {name.NamespaceName};",
                "",
            };
            if (!hasRealFunction)
            {
                lines.Add($"[global::System.Obsolete({CSharpLiteral(ShellTypeReason)}, false)]");
            }

            lines.AddRange(
            [
                $"public sealed {classModifier}partial class {name.ClassName}{interfaceClause}",
                "{",
                "    private nint __hosihikari_shim_handle;",
                "    private readonly bool _ownsHandle;",
                "",
                $"    public {name.ClassName}(nint handle) : this(handle, true) {{ }}",
                "",
                $"    internal {name.ClassName}(nint handle, bool ownsHandle)",
                "    {",
                "        __hosihikari_shim_handle = handle;",
                "        _ownsHandle = ownsHandle;",
                "    }",
                "",
                $"    public static {name.ClassName} Borrow(nint handle) => new {name.ClassName}(handle, false);",
                "",
                "    public nint Handle => __hosihikari_shim_handle;",
                "",
                "    internal nint ReleaseHandle()",
                "    {",
                "        if (__hosihikari_shim_handle == 0)",
                "        {",
                "            throw new global::System.ObjectDisposedException(\"handle\");",
                "        }",
                "",
                "        if (!_ownsHandle)",
                "        {",
                "            throw new global::System.InvalidOperationException(\"A borrowed handle cannot be released.\");",
                "        }",
                "",
                "        var __hs_handle = __hosihikari_shim_handle;",
                "        __hosihikari_shim_handle = 0;",
                "        return __hs_handle;",
                "    }",
            ]);

            var declarationMembers = members.TryGetValue(declaration.Id, out var ownMembers)
                ? ownMembers
                : [];
            if (plan.SyntheticMembers.TryGetValue(declaration.Id, out var syntheticMembers))
            {
                declarationMembers = declarationMembers
                    .Concat(syntheticMembers)
                    .GroupBy(member => member.Id, StringComparer.Ordinal)
                    .Select(group => group.First())
                    .OrderBy(member => member.Id, StringComparer.Ordinal)
                    .ToList();
            }

            if (declarationMembers.Count > 0)
            {
                var memberNames = BuildMemberNames(declarationMembers, plan, name.ClassName);
                foreach (var member in declarationMembers)
                {
                    // Synthetic support members feed by-value copy/destroy planning; they are
                    // not part of the public surface.
                    if (member.Access != "public"
                        || member.Id.Contains("@support:", StringComparison.Ordinal))
                    {
                        continue;
                    }

                    lines.Add("");
                    EmitMember(lines, member, memberNames[member.Id], name.ClassName, plan, hasDestroy);
                }
            }

            if (plan.FunctionsByDeclaration.TryGetValue(declaration.Id, out var declarationFunctions))
            {
                foreach (var helper in declarationFunctions
                             .Where(function => function.Kind is AbiFunctionKind.Cast
                                 or AbiFunctionKind.DirectorCreate)
                             .OrderBy(function => function.CSharpMemberName, StringComparer.Ordinal))
                {
                    lines.Add("");
                    EmitMethod(lines, helper.CSharpMemberName, helper);
                }
            }

            if (hasDestroy)
            {
                lines.Add("");
                EmitDispose(lines, destroy!);
            }

            lines.Add("}");

            var fileName = name.ClassName + "_" + CSharpNaming.ShortHash(declaration.Id) + ".g.cs";
            var path = Path.Combine(outputDirectory, "interop", declaration.Surface, fileName);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }

        EmitFreeFunctionClasses(outputDirectory, plan);
    }

    private static void EmitEnums(
        string outputDirectory,
        IReadOnlyList<DeclarationRecord> enums,
        IReadOnlyList<DeclarationRecord> typeDeclarations,
        IReadOnlyDictionary<string, List<MemberRecord>> members,
        IReadOnlyDictionary<string, DeclarationName> declarationNames)
    {
        if (enums.Count == 0)
        {
            return;
        }

        // Nested enums follow the nested-class naming rule: a parent that is itself a
        // declaration becomes a `_Nested` namespace segment, so a type and a namespace never
        // share one full name.
        var knownTypes = typeDeclarations
            .Select(declaration => declaration.QualifiedName)
            .Concat(enums.Select(declaration => declaration.QualifiedName))
            .ToHashSet(StringComparer.Ordinal);
        var enumNames = CSharpNaming.BuildDeclarationNames(enums, knownTypes);

        var occupied = declarationNames.Values
            .Select(name => name.NamespaceName + "." + name.ClassName)
            .ToHashSet(StringComparer.Ordinal);
        foreach (var declaration in enums)
        {
            var name = enumNames[declaration.Id];
            if (!occupied.Add(name.NamespaceName + "." + name.ClassName))
            {
                enumNames[declaration.Id] = new DeclarationName(
                    name.NamespaceName,
                    name.NamespacePath,
                    name.ClassName + "_" + CSharpNaming.ShortHash(declaration.Id));
            }
        }

        foreach (var declaration in enums)
        {
            var name = enumNames[declaration.Id];
            var values = members.TryGetValue(declaration.Id, out var own)
                ? own
                    .Where(member => member.Kind == "enum_value" && member.Access == "public")
                    .Select(member => (Member: member, Value: EnumValue(member)))
                    .OrderBy(pair => pair.Value)
                    .ThenBy(pair => pair.Member.Name, StringComparer.Ordinal)
                    .ToList()
                : [];

            var valueNames = BuildEnumValueNames(values.Select(pair => pair.Member).ToList());
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "",
                $"namespace {name.NamespaceName};",
                "",
            };
            if (values.Count == 0)
            {
                lines.Add($"[global::System.Obsolete({CSharpLiteral(EmptyEnumReason)}, false)]");
            }

            lines.Add($"public enum {name.ClassName} : {EnumUnderlyingType(declaration.UnderlyingType, values.Select(pair => pair.Value).ToList())}");
            lines.Add("{");
            foreach (var pair in values)
            {
                lines.Add($"    {valueNames[pair.Member.Id]} = {pair.Value.ToString(CultureInfo.InvariantCulture)},");
            }

            lines.Add("}");

            var fileName = name.ClassName + "_" + CSharpNaming.ShortHash(declaration.Id) + ".g.cs";
            var path = Path.Combine(outputDirectory, "interop", declaration.Surface, fileName);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static BigInteger EnumValue(MemberRecord member) =>
        BigInteger.TryParse(
            member.Value,
            NumberStyles.AllowLeadingSign,
            CultureInfo.InvariantCulture,
            out var value)
            ? value
            : throw new InvalidOperationException($"Enum value '{member.Id}' has no integer value.");

    private static Dictionary<string, string> BuildEnumValueNames(IReadOnlyList<MemberRecord> values)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in values.GroupBy(member => TypeNames.Sanitize(member.Name), StringComparer.Ordinal))
        {
            var duplicate = group.Count() > 1;
            foreach (var member in group)
            {
                var name = TypeNames.Sanitize(member.Name);
                names[member.Id] = duplicate
                    ? name + "_" + CSharpNaming.ShortHash(member.Id)
                    : name;
            }
        }

        return names;
    }

    // The native declaration names the underlying integer. Windows and Linux disagree on
    // the width of `long`, so the spelling only picks the first candidate and the values
    // widen it when they do not fit. The C# enum carries constants; signatures keep their
    // integer projection, so this width never reaches the ABI.
    private static string EnumUnderlyingType(string? nativeType, IReadOnlyList<BigInteger> values)
    {
        var candidate = nativeType?.Trim() switch
        {
            "bool" => "byte",
            "char" or "signed char" or "int8_t" => "sbyte",
            "unsigned char" or "char8_t" or "uint8_t" => "byte",
            "short" or "int16_t" => "short",
            "unsigned short" or "uint16_t" or "char16_t" => "ushort",
            "int" or "int32_t" => "int",
            "unsigned int" or "uint32_t" => "uint",
            "long" => "int",
            "unsigned long" => "uint",
            "long long" or "int64_t" or "ptrdiff_t" => "long",
            "unsigned long long" or "uint64_t" or "size_t" => "ulong",
            _ => "int",
        };

        if (values.Count == 0)
        {
            return candidate;
        }

        var min = values.Min();
        var max = values.Max();
        string[] signed = ["sbyte", "short", "int", "long"];
        string[] unsigned = ["byte", "ushort", "uint", "ulong"];
        var unsignedCandidate = candidate is "byte" or "ushort" or "uint" or "ulong";
        var ladder = unsignedCandidate && min.Sign >= 0 ? unsigned : signed;
        // The declared width is the floor; values only widen it.
        var start = Math.Max(0, Array.IndexOf(ladder, candidate));
        for (var index = start; index < ladder.Length; index++)
        {
            if (ConstantFields.Fits(ladder[index], min) && ConstantFields.Fits(ladder[index], max))
            {
                return ladder[index];
            }
        }

        return max.Sign >= 0 ? "ulong" : "long";
    }

    private static void EmitFreeFunctionClasses(string outputDirectory, AbiPlan plan)
    {
        var functionsByKey = plan.Functions
            .Where(function => function.Kind == AbiFunctionKind.FreeFunction)
            .GroupBy(function => (
                Surface: function.Surface,
                NamespaceName: function.ClassName.NamespaceName,
                ClassName: function.ClassName.ClassName))
            .ToDictionary(group => group.Key, group => group.ToList());
        var stubsByKey = plan.FunctionStubs
            .GroupBy(stub => (
                Surface: stub.Surface,
                NamespaceName: stub.NamespaceName,
                ClassName: stub.ClassName))
            .ToDictionary(group => group.Key, group => group.ToList());

        var keys = functionsByKey.Keys
            .Concat(stubsByKey.Keys)
            .Distinct()
            .OrderBy(key => key.Surface, StringComparer.Ordinal)
            .ThenBy(key => key.NamespaceName, StringComparer.Ordinal)
            .ThenBy(key => key.ClassName, StringComparer.Ordinal)
            .ToList();

        foreach (var key in keys)
        {
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "",
                $"namespace {key.NamespaceName};",
                "",
                $"public static unsafe partial class {key.ClassName}",
                "{",
            };
            var first = true;
            if (functionsByKey.TryGetValue(key, out var functions))
            {
                foreach (var function in functions.OrderBy(function => function.CSharpMemberName, StringComparer.Ordinal))
                {
                    if (!first)
                    {
                        lines.Add("");
                    }

                    first = false;
                    EmitMethod(lines, function.CSharpMemberName, function);
                }
            }

            if (stubsByKey.TryGetValue(key, out var stubs))
            {
                foreach (var stub in stubs.OrderBy(stub => stub.CSharpMemberName, StringComparer.Ordinal))
                {
                    if (!first)
                    {
                        lines.Add("");
                    }

                    first = false;
                    EmitFunctionStub(lines, stub);
                }
            }

            lines.Add("}");
            var fileName = key.ClassName + "_"
                + CSharpNaming.ShortHash(key.NamespaceName + "." + key.ClassName) + ".g.cs";
            var path = Path.Combine(outputDirectory, "interop", key.Surface, fileName);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static void EmitFunctionStub(List<string> lines, AbiFunctionStub stub)
    {
        var stubMessage = $"BindingShim cannot project this member: {stub.Reason}.";
        EmitUnsupportedAttribute(lines, stubMessage);
        var returnType = TypeNames.ToCSharpType(new TypeRef
        {
            Kind = "fundamental",
            Canonical = stub.ReturnType,
        });
        lines.Add($"    public static {returnType} {stub.CSharpMemberName}({CSharpParameters(stub.Parameters)}) =>");
        lines.Add($"        throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
    }

    private static void EmitNativeMethods(string outputDirectory, AbiPlan plan)
    {
        foreach (var surface in plan.Functions
                     .Select(function => function.Surface)
                     .Distinct(StringComparer.Ordinal)
                     .OrderBy(surface => surface, StringComparer.Ordinal))
        {
            var functions = plan.FunctionsForSurface(surface)
                .OrderBy(function => function.Index)
                .ToList();
            if (functions.Count == 0)
            {
                continue;
            }

            var namespaceName = $"Hosihikari.Bindings.{TypeNames.SurfaceNamespace(surface)}.Interop";
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "using System.Runtime.CompilerServices;",
                "",
                $"namespace {namespaceName};",
                "",
                "public static unsafe class NativeMethods",
                "{",
            };

            // The CLR rejects a type with more than 65535 fields, so a large surface is
            // partitioned into chunk structs that keep the native table layout.
            var chunkCount = (functions.Count + TableChunkSize - 1) / TableChunkSize;
            for (var chunk = 0; chunk < chunkCount; chunk++)
            {
                lines.Add("    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]");
                lines.Add($"    internal struct TableChunk{chunk}");
                lines.Add("    {");
                foreach (var function in functions.Skip(chunk * TableChunkSize).Take(TableChunkSize))
                {
                    lines.Add($"        public {CSharpFunctionPointerType(function)} {function.TableField};");
                }

                lines.Add("    }");
                lines.Add("");
            }

            lines.Add("    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]");
            lines.Add("    internal struct Table");
            lines.Add("    {");
            lines.Add("        public uint Version;");
            lines.Add("        public uint Size;");
            for (var chunk = 0; chunk < chunkCount; chunk++)
            {
                lines.Add($"        public TableChunk{chunk} C{chunk};");
            }

            lines.AddRange(
            [
                "    }",
                "",
                "    private static global::Hosihikari.Bindings.Abi.ShimLibrary? s_library;",
                "",
                "    public static string? GetLastError() => s_library?.GetLastError();",
                "",
                "    internal static Table* TablePtr",
                "    {",
                "        get",
                "        {",
                "            if (s_library is null)",
                "            {",
                "                throw new global::System.InvalidOperationException(\"BindingShim is not loaded. Call NativeMethods.Load(path) first.\");",
                "            }",
                "",
                "            return (Table*)s_library.Table;",
                "        }",
                "    }",
                "",
                "    public static void Load(string nativeLibraryPath)",
                "    {",
                "        s_library = global::Hosihikari.Bindings.Abi.ShimLibrary.Load(nativeLibraryPath, 1, (uint)sizeof(Table));",
                "    }",
                "}",
            ]);

            if (string.Equals(surface, "endstone", StringComparison.Ordinal))
            {
                var loadIndex = lines.FindIndex(line => line.Contains("s_library = ", StringComparison.Ordinal));
                if (loadIndex >= 0)
                {
                    lines.Insert(
                        loadIndex + 1,
                        "        s_getServer = (delegate* unmanaged[Cdecl]<void*>)s_library.GetExport(\"hosihikari_endstone_get_server\");");
                }

                lines.InsertRange(lines.Count - 1,
                [
                    "    private static delegate* unmanaged[Cdecl]<void*> s_getServer;",
                    "",
                    "    public static nint GetServer()",
                    "    {",
                    "        if (s_getServer == null)",
                    "        {",
                    "            throw new global::System.InvalidOperationException(\"BindingShim is not loaded. Call NativeMethods.Load(path) first.\");",
                    "        }",
                    "",
                    "        var server = s_getServer();",
                    "        if (server == null)",
                    "        {",
                    "            throw new global::System.InvalidOperationException(GetLastError() ?? \"Failed to get the Endstone server.\");",
                    "        }",
                    "",
                    "        return (nint)server;",
                    "    }",
                    "",
                ]);
            }

            var path = Path.Combine(outputDirectory, "interop", surface, "NativeMethods.g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static string MapKeyType(AbiFunction function) =>
        function.MapKeyKind switch
        {
            AbiKind.StringView => "string",
            AbiKind.Opaque => "nint",
            _ => AbiPlan.CSharpType(function.MapKeyKind),
        };

    private static string MapValueType(AbiFunction function) =>
        function.MapValueKind switch
        {
            AbiKind.StringView => "string",
            AbiKind.Opaque => function.MapValueOwnership == ArrayElementOwnership.None
                ? "nint"
                : function.MapValueWrapperType!,
            _ => AbiPlan.CSharpType(function.MapValueKind),
        };

    private static string MapDecodeExpression(
        AbiKind kind,
        ArrayElementOwnership ownership,
        string? wrapperType,
        string valueField,
        string sizeField)
    {
        if (kind == AbiKind.StringView)
        {
            return $"global::System.Runtime.InteropServices.Marshal.PtrToStringUTF8((nint)__hs_entry.{valueField}, checked((int)__hs_entry.{sizeField}))!";
        }

        if (kind == AbiKind.Opaque)
        {
            return ownership == ArrayElementOwnership.None
                ? $"(nint)__hs_entry.{valueField}"
                : $"new {wrapperType}((nint)__hs_entry.{valueField})";
        }

        if (kind == AbiKind.Bool)
        {
            return $"__hs_entry.{valueField} != 0";
        }

        var type = AbiPlan.CSharpType(kind);
        return kind is AbiKind.I8 or AbiKind.I16 or AbiKind.I32 or AbiKind.I64 or AbiKind.ISize
            ? $"unchecked(({type})(long)__hs_entry.{valueField})"
            : $"unchecked(({type})__hs_entry.{valueField})";
    }

    private static void EmitCallableWrappers(string outputDirectory, AbiPlan plan)
    {
        foreach (var callable in plan.UsedCallables)
        {
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "",
                $"namespace {callable.NamespaceName};",
                "",
                $"public sealed unsafe class {callable.ClassName} : global::System.IDisposable",
                "{",
                "    private nint __hosihikari_shim_handle;",
                "",
                $"    public {callable.ClassName}(nint handle) => __hosihikari_shim_handle = handle;",
                "",
                "    public nint Handle => __hosihikari_shim_handle;",
                "",
            };
            EmitMethod(lines, "Invoke", callable.InvokeFunction!);
            lines.Add("");
            EmitDispose(lines, callable.DestroyFunction!, ownershipAware: false);
            lines.Add("}");

            var path = Path.Combine(outputDirectory, "interop", callable.Surface, callable.ClassName + ".g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static void EmitVariantWrappers(string outputDirectory, AbiPlan plan)
    {
        foreach (var variant in plan.UsedVariants)
        {
            var lines = new List<string>
            {
                "// <auto-generated/>",
                "#nullable enable",
                "#pragma warning disable CS0618",
                "",
                $"namespace {variant.NamespaceName};",
                "",
                $"public sealed unsafe class {variant.ClassName} : global::System.IDisposable",
                "{",
                "    private nint __hosihikari_shim_handle;",
                "",
                $"    public {variant.ClassName}(nint handle) => __hosihikari_shim_handle = handle;",
                "",
                "    public nint Handle => __hosihikari_shim_handle;",
            };

            for (var index = 0; index < variant.Alternatives.Count; index++)
            {
                lines.Add("");
                EmitVariantCreate(lines, variant, variant.Alternatives[index], variant.CreateFunctions[index]);
            }

            lines.Add("");
            lines.Add($"    public int Index => NativeMethods.{TableFieldAccess(variant.IndexFunction!)}((void*)__hosihikari_shim_handle);");
            foreach (var alternative in variant.Alternatives)
            {
                lines.Add("");
                lines.Add($"    public bool Is{alternative.ManagedName} => Index == {alternative.Index};");
            }

            for (var index = 0; index < variant.Alternatives.Count; index++)
            {
                lines.Add("");
                EmitVariantGetter(lines, variant.Alternatives[index], variant.GetFunctions[index]);
            }

            lines.Add("");
            lines.Add("    public void Dispose()");
            lines.Add("    {");
            lines.Add("        if (__hosihikari_shim_handle != 0)");
            lines.Add("        {");
            lines.Add($"            NativeMethods.{TableFieldAccess(variant.DestroyFunction!)}((void*)__hosihikari_shim_handle);");
            lines.Add("            __hosihikari_shim_handle = 0;");
            lines.Add("        }");
            lines.Add("    }");
            lines.Add("}");

            var path = Path.Combine(outputDirectory, "interop", variant.Surface, variant.ClassName + ".g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, string.Join("\n", lines) + "\n", new UTF8Encoding(false));
        }
    }

    private static void EmitVariantCreate(
        List<string> lines,
        VariantAbiInfo variant,
        VariantAlternative alternative,
        AbiFunction create)
    {
        var parameterType = alternative.Kind switch
        {
            VariantAlternativeKind.String => "string",
            VariantAlternativeKind.Record => alternative.WrapperType!,
            VariantAlternativeKind.Pointer => "nint",
            _ => AbiPlan.CSharpType(alternative.ScalarKind),
        };
        lines.Add($"    public static {variant.ClassName} Create{alternative.ManagedName}({parameterType} value)");
        lines.Add("    {");
        if (alternative.Kind == VariantAlternativeKind.String)
        {
            lines.Add("        var __hs_stringBytes = global::System.Text.Encoding.UTF8.GetBytes(value);");
            lines.Add("        fixed (byte* __hs_stringData = __hs_stringBytes)");
            lines.Add("        {");
            lines.Add($"            var handle = NativeMethods.{TableFieldAccess(create)}(__hs_stringData, (nuint)__hs_stringBytes.Length);");
            EmitVariantHandleCheck(lines, variant.ClassName, "            ");
            lines.Add("        }");
        }
        else
        {
            var argument = alternative.Kind switch
            {
                VariantAlternativeKind.Record => "(void*)value.Handle",
                VariantAlternativeKind.Pointer => "(void*)value",
                _ => "value",
            };
            lines.Add($"        var handle = NativeMethods.{TableFieldAccess(create)}({argument});");
            EmitVariantHandleCheck(lines, variant.ClassName, "        ");
        }

        lines.Add("    }");
    }

    private static void EmitVariantHandleCheck(List<string> lines, string className, string indent)
    {
        lines.Add(indent + "if (handle == null)");
        lines.Add(indent + "{");
        lines.Add(indent + "    throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"BindingShim create call failed.\");");
        lines.Add(indent + "}");
        lines.Add(indent + $"return new {className}((nint)handle);");
    }

    private static void EmitVariantGetter(List<string> lines, VariantAlternative alternative, AbiFunction getter)
    {
        var returnType = alternative.Kind switch
        {
            VariantAlternativeKind.String => "string?",
            VariantAlternativeKind.Record => alternative.WrapperType + "?",
            VariantAlternativeKind.Pointer => "nint?",
            _ => AbiPlan.CSharpType(alternative.ScalarKind) + "?",
        };
        lines.Add($"    public {returnType} As{alternative.ManagedName}()");
        lines.Add("    {");
        lines.Add($"        if (Index != {alternative.Index})");
        lines.Add("        {");
        lines.Add("            return null;");
        lines.Add("        }");
        lines.Add("");
        switch (alternative.Kind)
        {
            case VariantAlternativeKind.String:
                lines.Add($"        var __hs_view = NativeMethods.{TableFieldAccess(getter)}((void*)__hosihikari_shim_handle);");
                lines.Add("        return __hs_view.Data == null ? string.Empty : global::System.Text.Encoding.UTF8.GetString(__hs_view.Data, checked((int)__hs_view.Size));");
                break;
            case VariantAlternativeKind.Record:
                lines.Add($"        var __hs_handle = NativeMethods.{TableFieldAccess(getter)}((void*)__hosihikari_shim_handle);");
                lines.Add($"        return __hs_handle == null ? null : new {alternative.WrapperType}((nint)__hs_handle);");
                break;
            case VariantAlternativeKind.Pointer:
                lines.Add($"        var __hs_pointer = NativeMethods.{TableFieldAccess(getter)}((void*)__hosihikari_shim_handle);");
                lines.Add("        return __hs_pointer == null ? null : (nint)__hs_pointer;");
                break;
            default:
                lines.Add(alternative.ScalarKind == AbiKind.Bool
                    ? $"        return NativeMethods.{TableFieldAccess(getter)}((void*)__hosihikari_shim_handle) != 0;"
                    : $"        return NativeMethods.{TableFieldAccess(getter)}((void*)__hosihikari_shim_handle);");
                break;
        }

        lines.Add("    }");
    }

    private static string CSharpFunctionPointerType(AbiFunction function)
    {
        var types = new List<string>();
        if (function.Kind != AbiFunctionKind.Create && !function.Static)
        {
            types.Add("void*");
        }

        foreach (var parameter in function.Parameters)
        {
            if (parameter.IsVector || parameter.IsMap || parameter.Kind == AbiKind.Placeholder)
            {
                continue;
            }

            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    types.Add("byte*");
                    types.Add("nuint");
                    break;
                case AbiKind.Opaque:
                    types.Add("void*");
                    break;
                case AbiKind.Callback:
                    types.Add("void*");
                    types.Add("void*");
                    types.Add("void*");
                    break;
                case AbiKind.Shared:
                    types.Add("global::Hosihikari.Bindings.Abi.SharedHandleData");
                    break;
                default:
                    types.Add(AbiPlan.CSharpType(parameter.Kind));
                    break;
            }
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsVector))
        {
            types.Add(parameter.VectorElementOwnership == ArrayElementOwnership.PairCopy
                ? "global::Hosihikari.Bindings.Abi.MapEntry*"
                : parameter.VectorElementKind switch
                {
                    AbiKind.StringView => "global::Hosihikari.Bindings.Abi.StringView*",
                    AbiKind.Opaque => "void**",
                    _ => AbiPlan.CSharpType(parameter.VectorElementKind) + "*",
                });
            types.Add("nuint");
        }

        foreach (var _ in function.Parameters.Where(parameter => parameter.IsMap))
        {
            types.Add("global::Hosihikari.Bindings.Abi.ArrayView");
        }

        foreach (var parameter in function.Parameters.Where(parameter => parameter.IsOptional))
        {
            types.Add("bool");
        }

        if (function.NeedsPresenceFlag)
        {
            types.Add("bool*");
        }

        if (function.MutableStringOutRef)
        {
            types.Add("global::Hosihikari.Bindings.Abi.StringView*");
        }

        types.Add(AbiPlan.CSharpTableType(function.ReturnKind));
        return "delegate* unmanaged[Cdecl]<" + string.Join(", ", types) + ">";
    }

    private static Dictionary<string, string> BuildMemberNames(
        IReadOnlyList<MemberRecord> members, AbiPlan plan, string className)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var candidates = members
            .Select(member =>
            {
                var baseName = MemberBaseName(member);
                // C# forbids a member that shares its enclosing type's name. A class literally
                // named Destroy would otherwise collide with its own disposer.
                if (string.Equals(baseName, className, StringComparison.Ordinal))
                {
                    baseName += "_";
                }

                var planned = member.Kind == "constructor"
                    && plan.CreateByMember.TryGetValue(member.Id, out var create)
                        ? create
                        : member.Kind is "method" or "operator"
                            && plan.MethodByMember.TryGetValue(member.Id, out var method)
                                ? method
                                : null;
                var placeholderFree = planned is null
                    || !planned.Parameters.Any(parameter => parameter.Kind == AbiKind.Placeholder);
                return (Member: member, Name: baseName, Key: MemberKey(member, plan), PlaceholderFree: placeholderFree);
            })
            .ToList();

        foreach (var group in candidates.GroupBy(candidate => (candidate.Name, candidate.Key)))
        {
            var list = group.ToList();
            if (list.Count == 1)
            {
                result[list[0].Member.Id] = list[0].Name;
                continue;
            }

            // Hiding a placeholder parameter can collapse two overloads onto the same C#
            // signature. Keep the plain name for the overload that never had a placeholder
            // and suffix only the collapsed ones; a genuine overload collision still
            // suffixes every member.
            var plainId = list.Count(candidate => candidate.PlaceholderFree) == 1
                ? list.Find(candidate => candidate.PlaceholderFree).Member.Id
                : null;
            foreach (var candidate in list)
            {
                var name = candidate.Member.Id == plainId
                    ? candidate.Name
                    : candidate.Name + "_" + CSharpNaming.ShortHash(candidate.Member.Id);
                result[candidate.Member.Id] = name;
            }
        }

        return result;
    }

    private static string MemberKey(MemberRecord member, AbiPlan plan)
    {
        AbiFunction? planned = null;
        if (member.Kind == "constructor" && plan.CreateByMember.TryGetValue(member.Id, out var create))
        {
            planned = create;
        }
        else if (member.Kind is "method" or "operator"
            && plan.MethodByMember.TryGetValue(member.Id, out var method))
        {
            planned = method;
        }

        if (planned is not null)
        {
            return EmittedParameterTypes(planned);
        }

        return member.Kind is "method" or "function" or "operator" or "constructor" or "destructor"
            ? StubParameterTypes(member)
            : "field";
    }

    // C# distinguishes overloads by parameter type alone, so the key must be the type as
    // written. AbiFunction -> C# is not injective: a stubbed member and a planned one with
    // the same spelling, or a by-value record and its `T?` form, collapse to one signature.
    // Keying on the planned ABI kind would keep them apart and emit CS0111.
    private static string EmittedParameterTypes(AbiFunction function)
    {
        var types = new List<string>();
        foreach (var parameter in function.Parameters)
        {
            if (parameter.Kind == AbiKind.Placeholder)
            {
                continue;
            }

            if (parameter.Kind == AbiKind.Callback)
            {
                types.Add("nint");
                types.Add("nint");
                types.Add("nint");
                continue;
            }

            var type = CSharpDeclarationType(parameter);
            if (function.MutableStringOutRef && parameter.IsMutableString)
            {
                type = "ref " + type;
            }

            // A generated wrapper and SharedHandle are classes, so `T` and `T?` are one
            // type to the overload resolver. Only a nullable value type is distinct.
            if (type.EndsWith("?", StringComparison.Ordinal)
                && parameter.Kind is AbiKind.Opaque or AbiKind.Shared)
            {
                type = type[..^1];
            }

            types.Add(type);
        }

        return string.Join(",", types);
    }

    private static string StubParameterTypes(MemberRecord member)
    {
        if (member.Signature is null)
        {
            return "";
        }

        var types = new List<string>();
        foreach (var parameter in member.Signature.Parameters)
        {
            types.Add(TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type }));
        }

        return string.Join(",", types);
    }

    private static string? ParameterKey(AbiParameter parameter) =>
        parameter.Kind == AbiKind.Placeholder
            ? null
            : parameter.IsUniquePtrParam
            ? "unique_ptr:" + parameter.NativePointee
            : parameter.Kind == AbiKind.Shared
            ? "shared:" + AbiPlan.CSharpParameterType(parameter)
            : parameter.IsMap
            ? "map:" + parameter.NativeType
            : parameter.IsVector
            ? "vector:" + CSharpDeclarationType(parameter)
            : parameter.IsOptionalRef
                ? "optional_ref:" + parameter.OptionalRefInnerType
                : parameter.IsOptional
                    ? "optional:" + parameter.OptionalInnerType
                    : parameter.Kind == AbiKind.Callback
                    ? "callback:" + parameter.Callback!.NativeType
                    : parameter.Kind == AbiKind.Opaque && parameter.WrapperType is not null
                    ? "opaque:" + parameter.WrapperType
                    : AbiPlan.CSharpParameterType(parameter);

    private static string MemberBaseName(MemberRecord member) => member.Kind switch
    {
        "constructor" => "Create",
        "destructor" => "Destroy",
        "operator" => OperatorName(member),
        _ => TypeNames.Sanitize(member.Name),
    };

    private static string OperatorName(MemberRecord member)
    {
        return member.Name switch
        {
            "operator==" => "operator_equal",
            "operator!=" => "operator_not_equal",
            "operator<" => "operator_less",
            "operator<=" => "operator_less_equal",
            "operator>" => "operator_greater",
            "operator>=" => "operator_greater_equal",
            "operator<=>" => "operator_compare",
            "operator+" => "operator_add",
            "operator-" => "operator_subtract",
            "operator*" => "operator_multiply",
            "operator/" => "operator_divide",
            "operator%" => "operator_modulo",
            "operator[]" => "operator_index",
            "operator()" => "operator_call",
            "operator=" => "operator_assign",
            _ => BuildConversionOperatorName(member),
        };
    }

    private static string BuildConversionOperatorName(MemberRecord member)
    {
        var target = member.Name.StartsWith("operator ", StringComparison.Ordinal)
            ? member.Name["operator ".Length..]
            : member.Name;
        var name = TypeNames.Sanitize(target).TrimStart('@');
        if (name.Length > 60)
        {
            name = name[..60] + "_" + CSharpNaming.ShortHash(member.Id);
        }

        return "operator_" + name;
    }

    private static void EmitMember(
        List<string> lines,
        MemberRecord member,
        string name,
        string className,
        AbiPlan plan,
        bool hasDestroy)
    {
        var stubMessage = StubMessage(plan, member);
        switch (member.Kind)
        {
            case "field":
            case "static_field":
                if (member.Kind == "static_field"
                    && member.Value is not null
                    && ConstantFields.TryCSharpConstant(member, out var constantType, out var constantLiteral))
                {
                    lines.Add($"    public const {constantType} {name} = {constantLiteral};");
                }
                else
                {
                    EmitField(lines, member, name, plan, stubMessage);
                }

                break;

            case "constructor":
                if (plan.CreateByMember.TryGetValue(member.Id, out var create))
                {
                    EmitCreate(lines, className, name, create);
                }
                else
                {
                    EmitUnsupportedAttribute(lines, stubMessage);
                    lines.Add($"    public static {className} {name}({CSharpParameters(member)}) =>");
                    lines.Add($"        throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
                }

                break;

            case "destructor":
                if (!hasDestroy)
                {
                    EmitUnsupportedAttribute(lines, stubMessage);
                    lines.Add($"    public void {name}() =>");
                    lines.Add($"        throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
                }

                break;

            case "method":
            case "operator":
                if (plan.MethodByMember.TryGetValue(member.Id, out var method))
                {
                    EmitMethod(lines, name, method);
                }
                else
                {
                    EmitMethodStub(lines, member, name, stubMessage);
                }

                break;

            case "function":
                EmitMethodStub(lines, member, name, stubMessage);
                break;

            default:
                lines.Add($"    // member kind '{member.Kind}' is not emitted by the stub");
                break;
        }
    }

    private static void EmitField(
        List<string> lines,
        MemberRecord member,
        string name,
        AbiPlan plan,
        string stubMessage)
    {
        var hasGetter = plan.GetByMember.TryGetValue(member.Id, out var getter);
        var hasSetter = plan.SetByMember.TryGetValue(member.Id, out var setter);
        var modifier = member.Static ? "static " : "";
        if (!hasGetter && !hasSetter)
        {
            var type = TypeNames.ToCSharpType(member.Type);
            EmitUnsupportedAttribute(lines, stubMessage);
            lines.Add($"    public {modifier}{type} {name}");
            lines.Add("    {");
            lines.Add($"        get => throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
            lines.Add($"        set => throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
            lines.Add("    }");
            return;
        }

        var propertyType = hasGetter && getter!.ReturnWrapperType is not null
            ? getter.ReturnWrapperType
            : AbiPlan.CSharpPropertyType((getter ?? setter!).ReturnKind);
        var propertyName = hasGetter && getter!.FieldAddress ? name + "_Address" : name;
        if (hasGetter && getter!.FieldAddress)
        {
            lines.Add("    // The native field type is not projected; this is the address of the field storage.");
        }

        lines.Add($"    public {modifier}{propertyType} {propertyName}");
        lines.Add("    {");
        if (hasGetter)
        {
            var self = getter!.Static ? "" : "(void*)__hosihikari_shim_handle";
            var call = $"NativeMethods.{TableFieldAccess(getter)}({self})";
            switch (getter.ReturnKind)
            {
                case AbiKind.StringView:
                    lines.Add("        get");
                    lines.Add("        {");
                    lines.Add($"            var view = {call};");
                    lines.Add("            return global::System.Text.Encoding.UTF8.GetString(view.Data, checked((int)view.Size));");
                    lines.Add("        }");
                    break;
                case AbiKind.Opaque when getter.ReturnWrapperType is not null:
                    lines.Add($"        get => new {getter.ReturnWrapperType}((nint){call}, false);");
                    break;
                case AbiKind.Opaque:
                    lines.Add($"        get => (nint){call};");
                    break;
                case AbiKind.Bool:
                    lines.Add($"        get => {call} != 0;");
                    break;
                default:
                    lines.Add($"        get => {call};");
                    break;
            }
        }

        if (hasSetter)
        {
            var arguments = setter!.Static ? "value" : "(void*)__hosihikari_shim_handle, value";
            if (setter.Parameters.Count > 0 && setter.Parameters[0].Kind == AbiKind.Opaque)
            {
                arguments = setter.Static ? "(void*)value" : "(void*)__hosihikari_shim_handle, (void*)value";
            }

            lines.Add($"        set => NativeMethods.{TableFieldAccess(setter)}({arguments});");
        }

        lines.Add("    }");
    }

    private static void EmitCreate(List<string> lines, string className, string name, AbiFunction create)
    {
        var declarations = ParameterDeclarations(create);
        var stringIndices = FindStringParameters(create.Parameters);
        var arguments = string.Join(", ", BuildCallArgumentList(create.Parameters));
        // A constructor parameter may itself be called "handle" (ServerSoundInstance does);
        // the result local must not shadow it.
        var local = "handle";
        for (var index = 0; index < create.Parameters.Count; index++)
        {
            if (CSharpParameterName(create.Parameters, index) == local)
            {
                local = "__hs_handle";
                break;
            }
        }
        lines.Add($"    public static {className} {name}({declarations})");
        lines.Add("    {");
        EmitPinnedBody(
            lines,
            create.Parameters,
            stringIndices,
            FindVectorParameters(create.Parameters),
            "        ",
            bodyIndent =>
            {
                lines.Add(bodyIndent + $"var {local} = NativeMethods.{TableFieldAccess(create)}({arguments});");
                EmitHandleCheck(lines, bodyIndent, local);
                lines.Add(bodyIndent + $"return new {className}((nint){local});");
            });
        lines.Add("    }");
    }

    private static void EmitHandleCheck(List<string> lines, string indent = "        ", string local = "handle")
    {
        lines.Add(indent + $"if ({local} == null)");
        lines.Add(indent + "{");
        lines.Add(indent + "    throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"BindingShim create call failed.\");");
        lines.Add(indent + "}");
        lines.Add("");
    }

    private static void EmitMethod(List<string> lines, string name, AbiFunction method)
    {
        var modifier = method.Static ? "static " : "";
        var declarations = ParameterDeclarations(method);
        var stringIndices = FindStringParameters(method.Parameters);
        var callArguments = new List<string>();
        if (!method.Static)
        {
            callArguments.Add("(void*)__hosihikari_shim_handle");
        }

        callArguments.AddRange(BuildCallArgumentList(method.Parameters));
        if (method.NeedsPresenceFlag)
        {
            callArguments.Add("&__hs_hasValue");
        }

        if (method.MutableStringOutRef)
        {
            callArguments.Add("&__hs_strOut0");
        }

        var call = $"NativeMethods.{TableFieldAccess(method)}({string.Join(", ", callArguments)})";
        var returnType = method.ReturnKind switch
        {
            AbiKind.Void => "void",
            AbiKind.StringView => method.ReturnOptional ? "string?" : "string",
            AbiKind.Opaque => method.ReturnWrapperType is not null
                && (method.ReturnOwned || method.ReturnBorrowed)
                ? method.ReturnWrapperType + (method.ReturnNullable ? "?" : "")
                : method.ReturnOptional ? "nint?" : "nint",
            AbiKind.ArrayView => method.ArrayElementKind == AbiKind.StringView
                ? "string[]"
                : method.ArrayElementOwnership != ArrayElementOwnership.None
                    ? method.ArrayElementWrapperType + (method.ArrayElementOwnership == ArrayElementOwnership.OptionalRecordCopy ? "?[]" : "[]")
                    : method.ArrayElementKind == AbiKind.Shared
                        ? "global::Hosihikari.Bindings.Abi.SharedHandle[]"
                        : AbiPlan.CSharpType(method.ArrayElementKind) + "[]",
            AbiKind.Shared => "global::Hosihikari.Bindings.Abi.SharedHandle?",
            AbiKind.MapView => $"global::System.Collections.Generic.Dictionary<{MapKeyType(method)}, {MapValueType(method)}>",
            _ => AbiPlan.CSharpType(method.ReturnKind) + (method.ReturnOptional ? "?" : ""),
        };

        lines.Add($"    public {modifier}{returnType} {name}({declarations})");
        lines.Add("    {");
        if (method.NeedsPresenceFlag)
        {
            lines.Add("        var __hs_hasValue = false;");
        }

        var mutableStringIndex = method.MutableStringOutRef
            ? method.Parameters.FindIndex(parameter => parameter.IsMutableString)
            : -1;
        var mutableStringName = mutableStringIndex >= 0
            ? CSharpParameterName(method.Parameters, mutableStringIndex)
            : null;
        if (method.MutableStringOutRef)
        {
            lines.Add("        var __hs_strOut0 = default(global::Hosihikari.Bindings.Abi.StringView);");
        }

        EmitPinnedBody(
            lines,
            method.Parameters,
            stringIndices,
            FindVectorParameters(method.Parameters),
            "        ",
            bodyIndent =>
            {
                if (!method.MutableStringOutRef)
                {
                    EmitMethodBody(lines, method, call, bodyIndent);
                    return;
                }

                lines.Add(bodyIndent + "try");
                lines.Add(bodyIndent + "{");
                EmitMethodBody(lines, method, call, bodyIndent + "    ");
                lines.Add(bodyIndent + "}");
                lines.Add(bodyIndent + "finally");
                lines.Add(bodyIndent + "{");
                lines.Add(
                    bodyIndent
                    + $"    {mutableStringName} = __hs_strOut0.Data == null ? \"\" : global::System.Text.Encoding.UTF8.GetString(__hs_strOut0.Data, checked((int)__hs_strOut0.Size));");
                lines.Add(bodyIndent + "}");
            });
        lines.Add("    }");
    }

    private static void EmitMethodBody(List<string> lines, AbiFunction method, string call, string indent)
    {
        if (method.ReturnExpected)
        {
            if (method.ReturnKind == AbiKind.Void)
            {
                lines.Add(indent + $"{call};");
                lines.Add(indent + "if (!__hs_hasValue) { throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"Binding API call returned an error.\"); }");
                return;
            }

            lines.Add(indent + $"var __hs_expectedResult = {call};");
            lines.Add(indent + "if (!__hs_hasValue) { throw new global::System.InvalidOperationException(NativeMethods.GetLastError() ?? \"Binding API call returned an error.\"); }");
            call = "__hs_expectedResult";
        }

        switch (method.ReturnKind)
        {
            case AbiKind.Void:
                lines.Add(indent + call + ";");
                break;
            case AbiKind.StringView:
                lines.Add(indent + $"var __hs_view = {call};");
                if (method.ReturnOptional)
                {
                    lines.Add(indent + "return __hs_hasValue"
                        + " ? global::System.Text.Encoding.UTF8.GetString(__hs_view.Data, checked((int)__hs_view.Size))"
                        + " : null;");
                }
                else
                {
                    lines.Add(indent + "return global::System.Text.Encoding.UTF8.GetString(__hs_view.Data, checked((int)__hs_view.Size));");
                }

                break;
            case AbiKind.MapView:
            {
                var keyType = MapKeyType(method);
                var valueType = MapValueType(method);
                lines.Add(indent + $"var __hs_view = {call};");
                lines.Add(indent + "var __hs_items = (global::Hosihikari.Bindings.Abi.MapEntry*)__hs_view.Data;");
                lines.Add(indent + $"var __hs_result = new global::System.Collections.Generic.Dictionary<{keyType}, {valueType}>(checked((int)__hs_view.Size));");
                lines.Add(indent + "for (var __hs_i = 0; __hs_i < checked((int)__hs_view.Size); __hs_i++)");
                lines.Add(indent + "{");
                lines.Add(indent + "    var __hs_entry = __hs_items[__hs_i];");
                lines.Add(indent + $"    var __hs_key = {MapDecodeExpression(method.MapKeyKind, ArrayElementOwnership.None, null, "Key", "KeySize")};");
                lines.Add(indent + $"    var __hs_value = {MapDecodeExpression(method.MapValueKind, method.MapValueOwnership, method.MapValueWrapperType, "Value", "ValueSize")};");
                lines.Add(indent + "    __hs_result[__hs_key] = __hs_value;");
                lines.Add(indent + "}");
                lines.Add(indent + "return __hs_result;");
                break;
            }
            case AbiKind.ArrayView:
                lines.Add(indent + $"var __hs_view = {call};");
                if (method.ArrayElementKind == AbiKind.StringView)
                {
                    lines.Add(indent + "var __hs_items = (global::Hosihikari.Bindings.Abi.StringView*)__hs_view.Data;");
                    lines.Add(indent + "var __hs_result = __hs_view.Size == 0 ? global::System.Array.Empty<string>() : new string[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "for (var __hs_i = 0; __hs_i < __hs_result.Length; __hs_i++)");
                    lines.Add(indent + "{");
                    lines.Add(indent + "    __hs_result[__hs_i] = global::System.Text.Encoding.UTF8.GetString(__hs_items[__hs_i].Data, checked((int)__hs_items[__hs_i].Size));");
                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }
                else if (method.ArrayElementKind == AbiKind.Shared)
                {
                    lines.Add(indent + "var __hs_items = (global::Hosihikari.Bindings.Abi.SharedHandleData*)__hs_view.Data;");
                    lines.Add(indent + "var __hs_result = __hs_view.Size == 0 ? global::System.Array.Empty<global::Hosihikari.Bindings.Abi.SharedHandle>() : new global::Hosihikari.Bindings.Abi.SharedHandle[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "for (var __hs_i = 0; __hs_i < __hs_result.Length; __hs_i++)");
                    lines.Add(indent + "{");
                    lines.Add(indent + "    __hs_result[__hs_i] = global::Hosihikari.Bindings.Abi.SharedHandle.FromNative(__hs_items[__hs_i])!;");
                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }
                else if (method.ArrayElementOwnership != ArrayElementOwnership.None)
                {
                    var nullableElement = method.ArrayElementOwnership == ArrayElementOwnership.OptionalRecordCopy;
                    var wrapper = method.ArrayElementWrapperType!;
                    lines.Add(indent + "var __hs_items = (void**)__hs_view.Data;");
                    lines.Add(indent + $"var __hs_result = __hs_view.Size == 0 ? global::System.Array.Empty<{wrapper}>() : new {wrapper}{(nullableElement ? "?" : "")}[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "for (var __hs_i = 0; __hs_i < __hs_result.Length; __hs_i++)");
                    lines.Add(indent + "{");
                    if (nullableElement)
                    {
                        lines.Add(indent + "    var __hs_element = __hs_items[__hs_i];");
                        lines.Add(indent + $"    __hs_result[__hs_i] = __hs_element == null ? null : new {wrapper}((nint)__hs_element);");
                    }
                    else
                    {
                        lines.Add(indent + $"    __hs_result[__hs_i] = new {wrapper}((nint)__hs_items[__hs_i]);");
                    }

                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }
                else
                {
                    var elementType = AbiPlan.CSharpType(method.ArrayElementKind);
                    lines.Add(indent + $"var __hs_result = __hs_view.Size == 0 ? global::System.Array.Empty<{elementType}>() : new {elementType}[checked((int)__hs_view.Size)];");
                    lines.Add(indent + "if (__hs_view.Size > 0)");
                    lines.Add(indent + "{");
                    lines.Add(indent + $"    new global::System.ReadOnlySpan<{elementType}>(__hs_view.Data, checked((int)__hs_view.Size)).CopyTo(__hs_result);");
                    lines.Add(indent + "}");
                    lines.Add(indent + "return __hs_result;");
                }

                break;
            case AbiKind.Shared:
                lines.Add(indent + $"var __hs_shared = {call};");
                lines.Add(indent + "return global::Hosihikari.Bindings.Abi.SharedHandle.FromNative(__hs_shared);");
                break;
            case AbiKind.Opaque:
                if (method.ReturnWrapperType is not null
                    && (method.ReturnOwned || method.ReturnBorrowed))
                {
                    var constructor = method.ReturnBorrowed
                        ? $"new {method.ReturnWrapperType}((nint)__hs_handle, false)"
                        : $"new {method.ReturnWrapperType}((nint)__hs_handle)";
                    if (method.ReturnNullable)
                    {
                        lines.Add(indent + $"var __hs_handle = {call};");
                        var condition = method.ReturnOptional
                            ? "__hs_hasValue && __hs_handle != null"
                            : "__hs_handle != null";
                        lines.Add(indent + $"return {condition} ? {constructor} : null;");
                    }
                    else if (method.ReturnBorrowed)
                    {
                        lines.Add(indent + $"return new {method.ReturnWrapperType}((nint){call}, false);");
                    }
                    else
                    {
                        lines.Add(indent + $"return new {method.ReturnWrapperType}((nint){call});");
                    }
                }
                else if (method.ReturnOptional)
                {
                    lines.Add(indent + $"var __hs_handle = {call};");
                    lines.Add(indent + "return __hs_hasValue ? (nint)__hs_handle : null;");
                }
                else
                {
                    lines.Add(indent + $"return (nint){call};");
                }

                break;
            default:
                if (method.ReturnKind == AbiKind.Bool)
                {
                    if (method.ReturnOptional)
                    {
                        lines.Add(indent + $"var __hs_value = {call};");
                        lines.Add(indent + "return __hs_hasValue ? __hs_value != 0 : (bool?)null;");
                    }
                    else
                    {
                        lines.Add(indent + $"return {call} != 0;");
                    }

                    break;
                }

                if (method.ReturnOptional)
                {
                    lines.Add(indent + $"var __hs_value = {call};");
                    lines.Add(indent + $"return __hs_hasValue ? __hs_value : ({AbiPlan.CSharpType(method.ReturnKind)}?)null;");
                }
                else
                {
                    lines.Add(indent + $"return {call};");
                }

                break;
        }
    }

    private static void EmitMethodStub(
        List<string> lines,
        MemberRecord member,
        string name,
        string stubMessage)
    {
        var returnCanonical = member.Signature?.ReturnType ?? member.Type?.Canonical ?? "void";
        var returnType = TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = returnCanonical });
        var modifier = member.Static ? "static " : "";
        EmitUnsupportedAttribute(lines, stubMessage);
        lines.Add($"    public {modifier}{returnType} {name}({CSharpParameters(member)}) =>");
        lines.Add($"        throw new global::System.NotSupportedException({CSharpLiteral(stubMessage)});");
    }

    private static string ParameterDeclarations(AbiFunction function)
    {
        var parameters = function.Parameters;
        var declarations = new List<string>();
        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            if (parameter.Kind == AbiKind.Placeholder)
            {
                continue;
            }

            if (parameter.Kind == AbiKind.Callback)
            {
                var (invoke, userData, release) = CallbackNames(parameters, index);
                declarations.Add($"nint {invoke}");
                declarations.Add($"nint {userData}");
                declarations.Add($"nint {release}");
                continue;
            }

            var type = CSharpDeclarationType(parameter);
            if (function.MutableStringOutRef && parameter.IsMutableString)
            {
                type = "ref " + type;
            }

            declarations.Add($"{type} {CSharpParameterName(parameters, index)}");
        }

        return string.Join(", ", declarations);
    }

    /// <summary>
    /// The type written into a C# parameter list. Distinct native types can collapse to the
    /// same C# type, for example vectors of different pointer element types both use nint[].
    /// </summary>
    private static string CSharpDeclarationType(AbiParameter parameter) =>
        parameter.Kind == AbiKind.Shared
            ? "global::Hosihikari.Bindings.Abi.SharedHandle?"
            : parameter.IsMap
            ? $"global::System.Collections.Generic.Dictionary<{AbiPlan.CSharpMapKeyType(parameter.MapKeyKind)}, {AbiPlan.CSharpMapValueType(parameter)}>?"
            : parameter.IsVector
                ? parameter.VectorElementWrapperType is not null
                    ? parameter.VectorElementWrapperType
                        + (parameter.VectorElementOwnership == ArrayElementOwnership.OptionalRecordCopy ? "?[]" : "[]")
                    : parameter.VectorElementKind == AbiKind.StringView
                        ? "string[]"
                        : AbiPlan.CSharpType(parameter.VectorElementKind) + "[]"
                : parameter.IsOptional
                    ? parameter.Kind switch
                    {
                        AbiKind.StringView => "string?",
                        AbiKind.Opaque => (parameter.WrapperType ?? "nint") + "?",
                        _ => AbiPlan.CSharpType(parameter.Kind) + "?",
                    }
                    : AbiPlan.CSharpParameterType(parameter);

    private static (string Invoke, string UserData, string Release) CallbackNames(
        IReadOnlyList<AbiParameter> parameters,
        int index)
    {
        var name = CSharpParameterName(parameters, index);
        return (name + "Invoke", name + "UserData", name + "Release");
    }

