    private static IEnumerable<string> BuildCallArgumentList(
        IReadOnlyList<AbiParameter> parameters)
    {
        var optionalPresence = new List<string>();
        var vectorArguments = new List<string>();
        var mapArguments = new List<string>();
        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            if (parameter.Kind == AbiKind.Placeholder)
            {
                continue;
            }

            var name = CSharpParameterName(parameters, index);
            if (parameter.IsOptional)
            {
                optionalPresence.Add(parameter.Kind switch
                {
                    AbiKind.StringView => $"{name} is not null",
                    AbiKind.Opaque => $"{name} is not null",
                    _ => $"{name}.HasValue",
                });
            }

            if (parameter.IsVector)
            {
                vectorArguments.Add($"__hs_vectorData{index}");
                vectorArguments.Add($"(nuint)({name}?.Length ?? 0)");
                continue;
            }

            if (parameter.IsMap)
            {
                mapArguments.Add($"__hs_map{index}View");
                continue;
            }

            switch (parameter.Kind)
            {
                case AbiKind.StringView:
                    yield return $"__hs_stringData{index}";
                    yield return $"(nuint)__hs_stringByteCount{index}";
                    break;
                case AbiKind.Opaque:
                    if (parameter.IsUniquePtrParam)
                    {
                        yield return $"(void*){name}.ReleaseHandle()";
                    }
                    else if (parameter.IsOptional)
                    {
                        yield return parameter.WrapperType is not null
                            ? $"(void*)({name}?.Handle ?? 0)"
                            : $"(void*)({name} ?? 0)";
                    }
                    else if (parameter.WrapperType is not null)
                    {
                        yield return parameter.IsPointer
                            ? $"(void*)({name}?.Handle ?? 0)"
                            : $"(void*){name}.Handle";
                    }
                    else
                    {
                        yield return $"(void*){name}";
                    }

                    break;
                case AbiKind.Callback:
                {
                    var (invoke, userData, release) = CallbackNames(parameters, index);
                    yield return $"(void*){invoke}";
                    yield return $"(void*){userData}";
                    yield return $"(void*){release}";
                    break;
                }
                case AbiKind.Shared:
                    yield return $"{name}?.ToNative() ?? default(global::Hosihikari.Bindings.Abi.SharedHandleData)";
                    break;
                default:
                    yield return parameter.IsOptional
                        ? $"{name} ?? default({AbiPlan.CSharpType(parameter.Kind)})"
                        : name;
                    break;
            }
        }

        foreach (var argument in vectorArguments)
        {
            yield return argument;
        }

        foreach (var argument in mapArguments)
        {
            yield return argument;
        }

        foreach (var presence in optionalPresence)
        {
            yield return presence;
        }
    }

