    private static void EmitMapBlocks(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        IReadOnlyList<int> mapIndices,
        int position,
        string indent,
        Action<string> emitBody)
    {
        if (position >= mapIndices.Count)
        {
            emitBody(indent);
            return;
        }

        var index = mapIndices[position];
        var parameter = parameters[index];
        var name = CSharpParameterName(parameters, index);
        var suffix = index.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var keyHasStrings = parameter.MapKeyKind == AbiKind.StringView;
        var valueHasStrings = parameter.MapValueKind == AbiKind.StringView;
        lines.Add(indent + $"var __hs_map{suffix}Items = {name};");
        lines.Add(indent + $"var __hs_map{suffix}Count = __hs_map{suffix}Items?.Count ?? 0;");
        lines.Add(indent + $"var __hs_map{suffix}ByteTotal = 0;");
        lines.Add(indent + $"if (__hs_map{suffix}Items is not null)");
        lines.Add(indent + "{");
        lines.Add(indent + $"    foreach (var __hs_pair in __hs_map{suffix}Items)");
        lines.Add(indent + "    {");
        if (keyHasStrings)
        {
            lines.Add(indent + $"        __hs_map{suffix}ByteTotal += global::System.Text.Encoding.UTF8.GetByteCount(__hs_pair.Key ?? string.Empty);");
        }

        if (valueHasStrings)
        {
            lines.Add(indent + $"        __hs_map{suffix}ByteTotal += global::System.Text.Encoding.UTF8.GetByteCount(__hs_pair.Value ?? string.Empty);");
        }

        lines.Add(indent + "    }");
        lines.Add(indent + "}");
        lines.Add(indent + $"scoped global::System.Span<byte> __hs_map{suffix}Arena;");
        lines.Add(indent + $"if (__hs_map{suffix}ByteTotal <= 1024) {{ __hs_map{suffix}Arena = stackalloc byte[__hs_map{suffix}ByteTotal == 0 ? 1 : __hs_map{suffix}ByteTotal]; }} else {{ __hs_map{suffix}Arena = new byte[__hs_map{suffix}ByteTotal]; }}");
        lines.Add(indent + $"scoped global::System.Span<global::Hosihikari.Bindings.Abi.MapEntry> __hs_map{suffix}EntrySpan;");
        lines.Add(indent + $"if (__hs_map{suffix}Count <= 16) {{ __hs_map{suffix}EntrySpan = stackalloc global::Hosihikari.Bindings.Abi.MapEntry[__hs_map{suffix}Count == 0 ? 1 : __hs_map{suffix}Count]; }} else {{ __hs_map{suffix}EntrySpan = new global::Hosihikari.Bindings.Abi.MapEntry[__hs_map{suffix}Count]; }}");
        lines.Add(indent + $"fixed (byte* __hs_map{suffix}ArenaPtr = __hs_map{suffix}Arena)");
        lines.Add(indent + $"fixed (global::Hosihikari.Bindings.Abi.MapEntry* __hs_map{suffix}Data = __hs_map{suffix}EntrySpan)");
        lines.Add(indent + "{");
        var inner = indent + "    ";
        lines.Add(inner + $"var __hs_map{suffix}Offset = 0;");
        lines.Add(inner + $"var __hs_map{suffix}Index = 0;");
        lines.Add(inner + $"if (__hs_map{suffix}Items is not null)");
        lines.Add(inner + "{");
        var loopIndent = inner + "    ";
        lines.Add(loopIndent + $"foreach (var __hs_pair in __hs_map{suffix}Items)");
        lines.Add(loopIndent + "{");
        var encodeIndent = loopIndent + "    ";
        lines.Add(encodeIndent + "var __hs_entry = new global::Hosihikari.Bindings.Abi.MapEntry();");
        if (keyHasStrings)
        {
            EmitArenaStringEncode(
                lines,
                encodeIndent,
                "Key",
                "KeySize",
                $"__hs_map{suffix}KeyItem",
                $"__hs_map{suffix}KeyLength",
                "__hs_pair.Key",
                $"__hs_map{suffix}Arena",
                $"__hs_map{suffix}ArenaPtr",
                $"__hs_map{suffix}Offset");
        }
        else
        {
            EmitMapManagedEncode(
                lines,
                encodeIndent,
                "Key",
                "KeySize",
                parameter.MapKeyKind,
                ArrayElementOwnership.None,
                "__hs_pair.Key",
                $"__hs_map{suffix}Arena",
                $"__hs_map{suffix}Offset");
        }

        if (valueHasStrings)
        {
            EmitArenaStringEncode(
                lines,
                encodeIndent,
                "Value",
                "ValueSize",
                $"__hs_map{suffix}ValueItem",
                $"__hs_map{suffix}ValueLength",
                "__hs_pair.Value",
                $"__hs_map{suffix}Arena",
                $"__hs_map{suffix}ArenaPtr",
                $"__hs_map{suffix}Offset");
        }
        else
        {
            EmitMapManagedEncode(
                lines,
                encodeIndent,
                "Value",
                "ValueSize",
                parameter.MapValueKind,
                parameter.MapValueOwnership,
                "__hs_pair.Value",
                $"__hs_map{suffix}Arena",
                $"__hs_map{suffix}Offset");
        }

        lines.Add(encodeIndent + $"__hs_map{suffix}Data[__hs_map{suffix}Index++] = __hs_entry;");
        lines.Add(loopIndent + "}");
        lines.Add(inner + "}");
        lines.Add(inner + $"var __hs_map{suffix}View = new global::Hosihikari.Bindings.Abi.ArrayView {{ Data = __hs_map{suffix}Data, Size = (nuint)__hs_map{suffix}Count }};");
        EmitMapBlocks(lines, parameters, mapIndices, position + 1, inner, emitBody);
        lines.Add(indent + "}");
    }

    private static void EmitArenaStringEncode(
        List<string> lines,
        string indent,
        string field,
        string sizeField,
        string itemVariable,
        string lengthVariable,
        string expression,
        string arenaName,
        string arenaPointerName,
        string offsetName)
    {
        lines.Add(indent + $"var {itemVariable} = {expression} ?? string.Empty;");
        lines.Add(indent + $"var {lengthVariable} = global::System.Text.Encoding.UTF8.GetByteCount({itemVariable});");
        lines.Add(indent + $"global::System.Text.Encoding.UTF8.GetBytes({itemVariable}, {arenaName}.Slice({offsetName}, {lengthVariable}));");
        lines.Add(indent + $"__hs_entry.{field} = (ulong)({arenaPointerName} + {offsetName});");
        lines.Add(indent + $"__hs_entry.{sizeField} = (ulong){lengthVariable};");
        lines.Add(indent + $"{offsetName} += {lengthVariable};");
    }

    private static void EmitMapManagedEncode(
        List<string> lines,
        string indent,
        string field,
        string sizeField,
        AbiKind kind,
        ArrayElementOwnership ownership,
        string expression,
        string stringsName,
        string stringCountName)
    {
        if (kind == AbiKind.StringView)
        {
            lines.Add(indent + $"var __hs_{field}Bytes = global::System.Text.Encoding.UTF8.GetBytes({expression} ?? string.Empty);");
            lines.Add(indent + $"var __hs_{field}Ptr = global::System.Runtime.InteropServices.Marshal.AllocHGlobal(__hs_{field}Bytes.Length == 0 ? 1 : __hs_{field}Bytes.Length);");
            lines.Add(indent + $"if (__hs_{field}Bytes.Length > 0) {{ global::System.Runtime.InteropServices.Marshal.Copy(__hs_{field}Bytes, 0, __hs_{field}Ptr, __hs_{field}Bytes.Length); }}");
            lines.Add(indent + $"{stringsName}[{stringCountName}++] = __hs_{field}Ptr;");
            lines.Add(indent + $"__hs_entry.{field} = (ulong)__hs_{field}Ptr;");
            lines.Add(indent + $"__hs_entry.{sizeField} = (ulong)__hs_{field}Bytes.Length;");
            return;
        }

        if (kind == AbiKind.Opaque)
        {
            lines.Add(indent + (ownership == ArrayElementOwnership.None
                ? $"__hs_entry.{field} = unchecked((ulong)(nint)({expression}));"
                : $"__hs_entry.{field} = unchecked((ulong)({expression}).Handle);"));
            return;
        }

        if (kind == AbiKind.Bool)
        {
            lines.Add(indent + $"__hs_entry.{field} = ({expression}) ? 1UL : 0UL;");
            return;
        }

        if (kind == AbiKind.F32)
        {
            lines.Add(indent + $"__hs_entry.{field} = global::System.BitConverter.SingleToUInt32Bits({expression});");
            return;
        }

        if (kind == AbiKind.F64)
        {
            lines.Add(indent + $"__hs_entry.{field} = global::System.BitConverter.DoubleToUInt64Bits({expression});");
            return;
        }

        var signed = kind is AbiKind.I8 or AbiKind.I16 or AbiKind.I32 or AbiKind.I64 or AbiKind.ISize;
        lines.Add(indent + (signed
            ? $"__hs_entry.{field} = unchecked((ulong)(long)({expression}));"
            : $"__hs_entry.{field} = unchecked((ulong)({expression}));"));
    }

    private static void EmitPinnedBodyCore(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        IReadOnlyList<int> stringIndices,
        IReadOnlyList<int> vectorIndices,
        string indent,
        Action<string> emitBody)
    {
        EmitStringBuffers(lines, parameters, stringIndices, indent);
        EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, 0, indent, emitBody);
    }

    private static void EmitVectorBlocks(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        IReadOnlyList<int> stringIndices,
        IReadOnlyList<int> vectorIndices,
        int position,
        string indent,
        Action<string> emitBody)
    {
        if (position >= vectorIndices.Count)
        {
            EmitStringFixes(lines, parameters, stringIndices, 0, indent, emitBody);
            return;
        }

        var index = vectorIndices[position];
        var vector = parameters[index];
        var vectorName = CSharpParameterName(parameters, index);
        var suffix = index.ToString(System.Globalization.CultureInfo.InvariantCulture);
        if (vector.VectorElementOwnership == ArrayElementOwnership.PairCopy)
        {
            var keyHasStrings = vector.VectorPairKeyKind == AbiKind.StringView;
            var valueHasStrings = vector.VectorPairValueKind == AbiKind.StringView;
            lines.Add(indent + $"var __hs_vectorItems{suffix} = {vectorName} ?? global::System.Array.Empty<{vector.VectorElementWrapperType}>();");
            lines.Add(indent + $"var __hs_vectorCount{suffix} = __hs_vectorItems{suffix}.Length;");
            lines.Add(indent + $"var __hs_vectorByteTotal{suffix} = 0;");
            lines.Add(indent + $"for (var __hs_i{suffix} = 0; __hs_i{suffix} < __hs_vectorCount{suffix}; __hs_i{suffix}++)");
            lines.Add(indent + "{");
            lines.Add(indent + $"    var __hs_pair{suffix} = __hs_vectorItems{suffix}[__hs_i{suffix}];");
            if (keyHasStrings)
            {
                lines.Add(indent + $"    __hs_vectorByteTotal{suffix} += global::System.Text.Encoding.UTF8.GetByteCount(__hs_pair{suffix}.Key ?? string.Empty);");
            }

            if (valueHasStrings)
            {
                lines.Add(indent + $"    __hs_vectorByteTotal{suffix} += global::System.Text.Encoding.UTF8.GetByteCount(__hs_pair{suffix}.Value ?? string.Empty);");
            }

            lines.Add(indent + "}");
            lines.Add(indent + $"scoped global::System.Span<byte> __hs_vectorArena{suffix};");
            lines.Add(indent + $"if (__hs_vectorByteTotal{suffix} <= 1024) {{ __hs_vectorArena{suffix} = stackalloc byte[__hs_vectorByteTotal{suffix} == 0 ? 1 : __hs_vectorByteTotal{suffix}]; }} else {{ __hs_vectorArena{suffix} = new byte[__hs_vectorByteTotal{suffix}]; }}");
            lines.Add(indent + $"scoped global::System.Span<global::Hosihikari.Bindings.Abi.MapEntry> __hs_vectorEntrySpan{suffix};");
            lines.Add(indent + $"if (__hs_vectorCount{suffix} <= 16) {{ __hs_vectorEntrySpan{suffix} = stackalloc global::Hosihikari.Bindings.Abi.MapEntry[__hs_vectorCount{suffix} == 0 ? 1 : __hs_vectorCount{suffix}]; }} else {{ __hs_vectorEntrySpan{suffix} = new global::Hosihikari.Bindings.Abi.MapEntry[__hs_vectorCount{suffix}]; }}");
            lines.Add(indent + $"fixed (byte* __hs_vectorArenaPtr{suffix} = __hs_vectorArena{suffix})");
            lines.Add(indent + $"fixed (global::Hosihikari.Bindings.Abi.MapEntry* __hs_vectorData{suffix} = __hs_vectorEntrySpan{suffix})");
            lines.Add(indent + "{");
            var inner = indent + "    ";
            lines.Add(inner + $"var __hs_vectorOffset{suffix} = 0;");
            lines.Add(inner + $"for (var __hs_i{suffix} = 0; __hs_i{suffix} < __hs_vectorCount{suffix}; __hs_i{suffix}++)");
            lines.Add(inner + "{");
            lines.Add(inner + $"    var __hs_pair{suffix} = __hs_vectorItems{suffix}[__hs_i{suffix}];");
            lines.Add(inner + "    var __hs_entry = new global::Hosihikari.Bindings.Abi.MapEntry();");
            if (keyHasStrings)
            {
                EmitArenaStringEncode(
                    lines,
                    inner + "    ",
                    "Key",
                    "KeySize",
                    $"__hs_KeyItem{suffix}",
                    $"__hs_KeyLength{suffix}",
                    $"__hs_pair{suffix}.Key",
                    $"__hs_vectorArena{suffix}",
                    $"__hs_vectorArenaPtr{suffix}",
                    $"__hs_vectorOffset{suffix}");
            }
            else
            {
                EmitMapManagedEncode(
                    lines,
                    inner + "    ",
                    "Key",
                    "KeySize",
                    vector.VectorPairKeyKind,
                    ArrayElementOwnership.None,
                    $"__hs_pair{suffix}.Key",
                    $"__hs_vectorArena{suffix}",
                    $"__hs_vectorOffset{suffix}");
            }

            if (valueHasStrings)
            {
                EmitArenaStringEncode(
                    lines,
                    inner + "    ",
                    "Value",
                    "ValueSize",
                    $"__hs_ValueItem{suffix}",
                    $"__hs_ValueLength{suffix}",
                    $"__hs_pair{suffix}.Value",
                    $"__hs_vectorArena{suffix}",
                    $"__hs_vectorArenaPtr{suffix}",
                    $"__hs_vectorOffset{suffix}");
            }
            else
            {
                EmitMapManagedEncode(
                    lines,
                    inner + "    ",
                    "Value",
                    "ValueSize",
                    vector.VectorPairValueKind,
                    ArrayElementOwnership.None,
                    $"__hs_pair{suffix}.Value",
                    $"__hs_vectorArena{suffix}",
                    $"__hs_vectorOffset{suffix}");
            }

            lines.Add(inner + $"    __hs_vectorData{suffix}[__hs_i{suffix}] = __hs_entry;");
            lines.Add(inner + "}");
            EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, position + 1, inner, emitBody);
            lines.Add(indent + "}");
            return;
        }

        if (vector.VectorElementKind == AbiKind.StringView)
        {
            lines.Add(indent + $"var __hs_vectorItems{suffix} = {vectorName} ?? global::System.Array.Empty<string>();");
            lines.Add(indent + $"var __hs_vectorCount{suffix} = __hs_vectorItems{suffix}.Length;");
            lines.Add(indent + $"var __hs_vectorByteTotal{suffix} = 0;");
            lines.Add(indent + $"for (var __hs_i{suffix} = 0; __hs_i{suffix} < __hs_vectorCount{suffix}; __hs_i{suffix}++) {{ __hs_vectorByteTotal{suffix} += global::System.Text.Encoding.UTF8.GetByteCount(__hs_vectorItems{suffix}[__hs_i{suffix}] ?? string.Empty); }}");
            lines.Add(indent + $"scoped global::System.Span<byte> __hs_vectorArena{suffix};");
            lines.Add(indent + $"if (__hs_vectorByteTotal{suffix} <= 1024) {{ __hs_vectorArena{suffix} = stackalloc byte[__hs_vectorByteTotal{suffix} == 0 ? 1 : __hs_vectorByteTotal{suffix}]; }} else {{ __hs_vectorArena{suffix} = new byte[__hs_vectorByteTotal{suffix}]; }}");
            lines.Add(indent + $"scoped global::System.Span<global::Hosihikari.Bindings.Abi.StringView> __hs_vectorViews{suffix};");
            lines.Add(indent + $"if (__hs_vectorCount{suffix} <= 64) {{ __hs_vectorViews{suffix} = stackalloc global::Hosihikari.Bindings.Abi.StringView[__hs_vectorCount{suffix} == 0 ? 1 : __hs_vectorCount{suffix}]; }} else {{ __hs_vectorViews{suffix} = new global::Hosihikari.Bindings.Abi.StringView[__hs_vectorCount{suffix}]; }}");
            lines.Add(indent + $"fixed (byte* __hs_vectorArenaPtr{suffix} = __hs_vectorArena{suffix})");
            lines.Add(indent + $"fixed (global::Hosihikari.Bindings.Abi.StringView* __hs_vectorData{suffix} = __hs_vectorViews{suffix})");
            lines.Add(indent + "{");
            var inner = indent + "    ";
            lines.Add(inner + $"var __hs_vectorOffset{suffix} = 0;");
            lines.Add(inner + $"for (var __hs_i{suffix} = 0; __hs_i{suffix} < __hs_vectorCount{suffix}; __hs_i{suffix}++)");
            lines.Add(inner + "{");
            lines.Add(inner + $"    var __hs_item{suffix} = __hs_vectorItems{suffix}[__hs_i{suffix}] ?? string.Empty;");
            lines.Add(inner + $"    var __hs_length{suffix} = global::System.Text.Encoding.UTF8.GetByteCount(__hs_item{suffix});");
            lines.Add(inner + $"    global::System.Text.Encoding.UTF8.GetBytes(__hs_item{suffix}, __hs_vectorArena{suffix}.Slice(__hs_vectorOffset{suffix}, __hs_length{suffix}));");
            lines.Add(inner + $"    __hs_vectorData{suffix}[__hs_i{suffix}] = new global::Hosihikari.Bindings.Abi.StringView {{ Data = __hs_vectorArenaPtr{suffix} + __hs_vectorOffset{suffix}, Size = (nuint)__hs_length{suffix} }};");
            lines.Add(inner + $"    __hs_vectorOffset{suffix} += __hs_length{suffix};");
            lines.Add(inner + "}");
            EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, position + 1, inner, emitBody);
            lines.Add(indent + "}");
            return;
        }

        if (vector.VectorElementKind == AbiKind.Opaque)
        {
            if (vector.VectorElementWrapperType is null)
            {
                // Pointer elements have no wrapper type; the parameter is already nint[].
                lines.Add(indent + $"var __hs_vectorItems{suffix} = {vectorName} ?? global::System.Array.Empty<nint>();");
                lines.Add(indent + $"fixed (nint* __hs_vectorHandleData{suffix} = __hs_vectorItems{suffix})");
                lines.Add(indent + "{");
                lines.Add(indent + $"    var __hs_vectorData{suffix} = (void**)__hs_vectorHandleData{suffix};");
                EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, position + 1, indent + "    ", emitBody);
                lines.Add(indent + "}");
                return;
            }

            lines.Add(indent + $"var __hs_vectorItems{suffix} = {vectorName};");
            lines.Add(indent + $"var __hs_vectorHandles{suffix} = new nint[__hs_vectorItems{suffix}?.Length ?? 0];");
            lines.Add(indent + $"for (var __hs_i{suffix} = 0; __hs_i{suffix} < __hs_vectorHandles{suffix}.Length; __hs_i{suffix}++)");
            lines.Add(indent + "{");
            lines.Add(indent + $"    __hs_vectorHandles{suffix}[__hs_i{suffix}] = __hs_vectorItems{suffix}![__hs_i{suffix}]?.Handle ?? 0;");
            lines.Add(indent + "}");
            lines.Add(indent + $"fixed (nint* __hs_vectorHandleData{suffix} = __hs_vectorHandles{suffix})");
            lines.Add(indent + "{");
            lines.Add(indent + $"    var __hs_vectorData{suffix} = (void**)__hs_vectorHandleData{suffix};");
            EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, position + 1, indent + "    ", emitBody);
            lines.Add(indent + "}");
            return;
        }

        var elementType = AbiPlan.CSharpType(vector.VectorElementKind);
        lines.Add(indent + $"fixed ({elementType}* __hs_vectorData{suffix} = {vectorName})");
        lines.Add(indent + "{");
        EmitVectorBlocks(lines, parameters, stringIndices, vectorIndices, position + 1, indent + "    ", emitBody);
        lines.Add(indent + "}");
    }

    private static void EmitStringBuffers(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        IReadOnlyList<int> stringIndices,
        string indent)
    {
        foreach (var index in stringIndices)
        {
            var name = CSharpParameterName(parameters, index);
            var expression = parameters[index].IsOptional
                ? $"{name} ?? string.Empty"
                : name;
            lines.Add(indent + $"var __hs_stringByteCount{index} = global::System.Text.Encoding.UTF8.GetByteCount({expression});");
            lines.Add(indent + $"scoped global::System.Span<byte> __hs_stringBytes{index};");
            lines.Add(indent + $"if (__hs_stringByteCount{index} <= 256)");
            lines.Add(indent + "{");
            lines.Add(indent + $"    __hs_stringBytes{index} = stackalloc byte[__hs_stringByteCount{index} == 0 ? 1 : __hs_stringByteCount{index}];");
            lines.Add(indent + "}");
            lines.Add(indent + "else");
            lines.Add(indent + "{");
            lines.Add(indent + $"    __hs_stringBytes{index} = new byte[__hs_stringByteCount{index}];");
            lines.Add(indent + "}");
            lines.Add(indent + $"global::System.Text.Encoding.UTF8.GetBytes({expression}, __hs_stringBytes{index});");
        }
    }

    private static void EmitStringFixes(
        List<string> lines,
        IReadOnlyList<AbiParameter> parameters,
        IReadOnlyList<int> stringIndices,
        int position,
        string indent,
        Action<string> emitBody)
    {
        if (position >= stringIndices.Count)
        {
            emitBody(indent);
            return;
        }

        var index = stringIndices[position];
        lines.Add(indent + $"fixed (byte* __hs_stringData{index} = __hs_stringBytes{index})");
        lines.Add(indent + "{");
        EmitStringFixes(lines, parameters, stringIndices, position + 1, indent + "    ", emitBody);
        lines.Add(indent + "}");
    }

    private static string CSharpParameterName(IReadOnlyList<AbiParameter> parameters, int index)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        string? result = null;
        for (var position = 0; position <= index; position++)
        {
            var parameter = parameters[position];
            var candidate = TypeNames.Sanitize(
                string.IsNullOrWhiteSpace(parameter.Name)
                    ? "arg" + position.ToString(System.Globalization.CultureInfo.InvariantCulture)
                    : parameter.Name);
            var name = candidate;
            var counter = position;
            while (!used.Add(name))
            {
                name = candidate + counter.ToString(System.Globalization.CultureInfo.InvariantCulture);
                counter++;
            }

            if (position == index)
            {
                result = name;
            }
        }

        return result!;
    }

    private static void EmitDispose(List<string> lines, AbiFunction destroy, bool ownershipAware = true)
    {
        lines.Add("    public void Dispose()");
        lines.Add("    {");
        lines.Add("        if (__hosihikari_shim_handle != 0)");
        lines.Add("        {");
        if (ownershipAware)
        {
            lines.Add("            if (_ownsHandle)");
            lines.Add("            {");
            lines.Add($"                NativeMethods.{TableFieldAccess(destroy)}((void*)__hosihikari_shim_handle);");
            lines.Add("            }");
            lines.Add("");
        }
        else
        {
            lines.Add($"            NativeMethods.{TableFieldAccess(destroy)}((void*)__hosihikari_shim_handle);");
        }

        lines.Add("            __hosihikari_shim_handle = 0;");
        lines.Add("        }");
        lines.Add("    }");
    }

    private static string CSharpParameters(MemberRecord member) =>
        member.Signature is null ? "" : CSharpParameters(member.Signature.Parameters);

    private static string CSharpParameters(IReadOnlyList<ParameterInfo> parameters)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        var declarations = new List<string>();
        for (var index = 0; index < parameters.Count; index++)
        {
            var parameter = parameters[index];
            var candidate = TypeNames.Sanitize(
                string.IsNullOrWhiteSpace(parameter.Name)
                    ? "arg" + index.ToString(System.Globalization.CultureInfo.InvariantCulture)
                    : parameter.Name);
            var name = candidate;
            var counter = index;
            while (!used.Add(name))
            {
                name = candidate + counter.ToString(System.Globalization.CultureInfo.InvariantCulture);
                counter++;
            }

            declarations.Add($"{TypeNames.ToCSharpType(new TypeRef { Kind = "fundamental", Canonical = parameter.Type })} {name}");
        }

        return string.Join(", ", declarations);
    }
